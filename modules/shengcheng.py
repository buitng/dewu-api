def match_trend_words(product_info: dict, count: int = 3) -> list:
    """从趋势词中匹配相关话题"""
    if not state.trend_words:
        return []
    sku = product_info.get('sku', '').lower()
    color = product_info.get('color', '').lower()
    category = product_info.get('category', '').lower()
    keywords = [sku, color, category]
    # 品类相关关键词扩展
    category_keywords = {
        '上衣': ['衬衫', 't恤', '短袖', '卫衣', '针织', '外套', '夹克'],
        '裤装': ['裤子', '牛仔裤', '休闲裤', '工装裤', '短裤'],
        '鞋履': ['鞋子', '运动鞋', '板鞋', '老爹鞋', '帆布鞋'],
        '箱包': ['包包', '背包', '斜挎包', '手提包', '钱包'],
        '裙装': ['裙子', '连衣裙', '半身裙', '吊带裙'],
    }
    if category in category_keywords:
        keywords.extend(category_keywords[category])

    matched = []
    for word in state.trend_words:
        word_lower = word.lower().replace('#', '').strip()
        if not word_lower:
            continue
        for kw in keywords:
            if kw and kw in word_lower:
                if word_lower not in matched:
                    matched.append(word_lower if word_lower.startswith('#') else f'#{word_lower}')
                break
        if len(matched) >= count:
            break
    return matched


# 持久化去重：记录每个单品已使用的标题和文案
USED_CONTENT_FILE = Path(__file__).parent / 'used_content.json'

def load_used_content() -> dict:
    """加载已使用的内容记录"""
    if USED_CONTENT_FILE.exists():
        try:
            with open(USED_CONTENT_FILE, 'r', encoding='utf-8') as f:
                return json.load(f)
        except Exception:
            return {}
    return {}

def save_used_content(data: dict):
    """保存已使用的内容记录"""
    try:
        with open(USED_CONTENT_FILE, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
    except Exception as e:
        log(f'保存已使用内容记录失败: {e}')

def get_product_key(dir_path: str) -> str:
    """获取单品的唯一标识（文件夹路径的最后两级）"""
    p = Path(dir_path)
    # 用父文件夹名 + 文件夹名作为key，例如 "蓝V图/971CT6001烬余灰"
    return f"{p.parent.name}/{p.name}"

def generate_unique_content(product_info: dict, product_key: str, image_path: str = None, product_name: str = '') -> dict:
    """生成不重复的内容（考虑历史已使用的内容）"""
    used_data = load_used_content()
    used = used_data.get(product_key, {'titles': [], 'contents': []})
    
    # 最多尝试20次，确保不重复
    for _ in range(20):
        generated = generate_content_with_ai(product_info, image_path=image_path, product_name=product_name)
        content_key = generated['content'][:30]
        if generated['title'] not in used['titles'] and content_key not in used['contents']:
            # 记录已使用
            used['titles'].append(generated['title'])
            used['contents'].append(content_key)
            used_data[product_key] = used
            save_used_content(used_data)
            source = generated.get('source', 'unknown')
            log(f'  内容生成完成 (来源: {source})')
            return generated
    
    # 如果20次都重复了，说明模板用完了，重置记录并重新生成
    log(f'  警告：该单品已使用 {len(used["titles"])} 个不同模板，重置记录以继续生成')
    used_data[product_key] = {'titles': [], 'contents': []}
    save_used_content(used_data)
    return generate_content_with_ai(product_info, product_name=product_name)

def reset_used_content(product_key: str = None):
    """重置已使用的内容记录（用于清空任务时调用）"""
    if product_key:
        used_data = load_used_content()
        if product_key in used_data:
            del used_data[product_key]
            save_used_content(used_data)
    else:
        # 清空所有
        save_used_content({})


def extract_product_info_from_path(dir_path: str) -> dict:
    """从文件夹路径中提取商品信息（货号、颜色、品类）"""
    import re
    path = Path(dir_path)
    folder_name = path.name
    parent_name = path.parent.name if path.parent else ''
    
    # 提取货号（字母+数字组合，如971CT6001）
    sku = ''
    sku_match = re.search(r'[A-Za-z]+\d+[A-Za-z0-9]*', folder_name)
    if sku_match:
        sku = sku_match.group()
    
    # 提取颜色（常见颜色词）
    color = ''
    color_words = ['黑色', '白色', '灰色', '红色', '蓝色', '绿色', '黄色', '粉色', '紫色', '棕色', '米色', '卡其色', '藏青色', '酒红色', '军绿色', '天蓝色', '湖蓝色', '墨绿色', '浅灰色', '深灰色', '米白色', '奶白色', '燕麦色', '驼色', '焦糖色', '咖啡色', '杏色', '藕粉色', '玫红色', '橘色', '橙色', '青色', '靛蓝色', '宝蓝色', '雾霾蓝', '牛油果绿', '薄荷绿', '荧光绿', '荧光黄', '荧光粉', '金属色', '银色', '金色', '古铜色', '青铜色', '烬余灰', '高级灰', '水泥灰', '烟灰', '炭黑', '米灰', '燕麦灰']
    for cw in color_words:
        if cw in folder_name:
            color = cw.replace('色', '') if cw.endswith('色') else cw
            break
    
    # 提取品类（常见品类词）
    category = '服饰'
    category_words = ['T恤', 't恤', '衬衫', '卫衣', '外套', '夹克', '针织衫', '毛衣', '裤子', '休闲裤', '牛仔裤', '工装裤', '阔腿裤', '短裤', '裙子', '连衣裙', '半身裙', '鞋子', '运动鞋', '板鞋', '帆布鞋', '包包', '手提包', '双肩包', '帽子', '袜子', '手表', '眼镜', '围巾', '手套', '腰带', '领带', '马甲', '背心', '吊带', '抹胸', '皮衣', '风衣', '大衣', '羽绒服', '棉服', '西装', '西服', 'POLO', 'polo', ' Polo']
    for cw in category_words:
        if cw.lower() in folder_name.lower():
            category = cw.upper() if cw.lower() == 'polo' else cw
            break
    
    # 如果父目录有品类信息，也尝试提取
    if category == '服饰':
        for cw in category_words:
            if cw.lower() in parent_name.lower():
                category = cw.upper() if cw.lower() == 'polo' else cw
                break
    
    return {
        'sku': sku,
        'color': color,
        'category': category,
        'gender': 'neutral',  # 默认中性，发布时可以根据设置覆盖
    }


