def parse_ai_response(content: str) -> dict:
    """解析AI返回的JSON（多种方式尝试，增强后处理过滤）"""
    import re as re_mod
    
    if not content:
        return None
    
    # 方式1：直接解析
    try:
        data = json.loads(content)
        if isinstance(data, dict) and ('title' in data or 'content' in data):
            return data
    except json.JSONDecodeError:
        pass
    
    # 方式2：提取第一个{...}
    match = re_mod.search(r'\{.*\}', content, re_mod.DOTALL)
    if match:
        try:
            data = json.loads(match.group())
            if isinstance(data, dict) and ('title' in data or 'content' in data):
                return data
        except json.JSONDecodeError:
            pass
    
    # 方式3：提取title、content、topics、keywords字段
    title_match = re_mod.search(r'"title"\s*:\s*"([^"]+)"', content)
    content_match = re_mod.search(r'"content"\s*:\s*"([^"]+)"', content)
    topics_match = re_mod.search(r'"topics"\s*:\s*"([^"]+)"', content)
    keywords_match = re_mod.search(r'"keywords"\s*:\s*"([^"]+)"', content)
    if title_match and content_match:
        return {
            'title': title_match.group(1),
            'content': content_match.group(1),
            'topics': topics_match.group(1) if topics_match else '',
            'keywords': keywords_match.group(1) if keywords_match else '',
        }
    
    # 方式4：如果内容本身就是标题和文案（非JSON格式），尝试提取
    lines = content.strip().split('\n')
    if len(lines) >= 2:
        title = lines[0].strip().strip('#').strip()
        body = '\n'.join(lines[1:]).strip()
        if title and body:
            return {'title': title[:30], 'content': body, 'topics': ''}
    
    log(f'AI返回内容解析失败: {content[:100]}')
    return None



def compress_and_encode_image(image_path: str, max_size: int = 800, quality: int = 70) -> str:
    """压缩图片并转base64（用于AI图片识别）"""
    try:
        from PIL import Image
        import io
        import base64
        
        img = Image.open(image_path)
        # 转换为RGB
        if img.mode != 'RGB':
            img = img.convert('RGB')
        # 等比缩放
        w, h = img.size
        if max(w, h) > max_size:
            ratio = max_size / max(w, h)
            img = img.resize((int(w * ratio), int(h * ratio)), Image.LANCZOS)
        # 转base64
        buffer = io.BytesIO()
        img.save(buffer, format='JPEG', quality=quality)
        return base64.b64encode(buffer.getvalue()).decode('utf-8')
    except Exception as e:
        log(f'图片压缩失败: {e}')
        return None


