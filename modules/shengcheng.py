def call_chat_api(base_url: str, api_key: str, model: str, prompt: str, temperature: float = 0.85, max_tokens: int = 3000, image_base64: str = None) -> str:
    """调用OpenAI兼容的Chat API（支持豆包、DeepSeek、GPT、Moonshot等），带重试机制"""
    import time
    url = f"{base_url.rstrip('/')}/chat/completions"
    headers = {'Content-Type': 'application/json'}
    if api_key:
        headers['Authorization'] = f'Bearer {api_key}'
    # System Prompt：强制纯JSON输出，减少废话
    system_prompt = "你是一个只会输出纯JSON的机器人。你绝对不能使用任何套话、解释、前缀、后缀。用户要求什么，你就只输出什么。不要输出\"好的\"、\"以下是\"、\"希望对你有帮助\"等任何多余文字。直接输出JSON，不要加markdown代码块。"
    
    # 构建消息（支持图片识别）
    if image_base64:
        messages = [
            {'role': 'system', 'content': system_prompt},
            {'role': 'user', 'content': [
                {'type': 'text', 'text': prompt},
                {'type': 'image_url', 'image_url': {'url': f'data:image/jpeg;base64,{image_base64}'}}
            ]}
        ]
    else:
        messages = [
            {'role': 'system', 'content': system_prompt},
            {'role': 'user', 'content': prompt}
        ]
    
    payload = {
        'model': model,
        'messages': messages,
        'temperature': temperature,
        'max_tokens': max_tokens,
    }
    last_error = None
    for attempt in range(4):  # 最多重试4次（第1次+重试3次）
        try:
            if attempt > 0:
                log(f'AI API第{attempt + 1}次尝试...')
            resp = requests.post(url, headers=headers, json=payload, timeout=180)
            resp.raise_for_status()
            data = resp.json()
            return data['choices'][0]['message']['content'].strip()
        except requests.exceptions.ReadTimeout as e:
            last_error = e
            if attempt < 1:
                log(f'AI API调用超时（第{attempt + 1}次），等待3秒后重试...')
                time.sleep(3)
            else:
                raise
        except requests.exceptions.ConnectionError as e:
            last_error = e
            if attempt < 1:
                log(f'AI API连接失败（第{attempt + 1}次），等待3秒后重试...')
                time.sleep(3)
            else:
                raise
    raise last_error


